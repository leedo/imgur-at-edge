package media

var types = map[string]string{
	"image/jpeg":      "jpg",
	"image/gif":       "gif",
	"image/x-png":     "png",
	"image/png":       "png",
	"video/quicktime": "mov",
	"video/mp4":       "mp4",
}

var mimes = map[string]string{
	"jpg": "image/jpeg",
	"gif": "image/gif",
	"png": "image/png",
	"mov": "video/quicktime",
	"mp4": "video/mp4",
}

func GetExtension(mime string) (string, bool) {
	ext, ok := types[mime]
	return ext, ok
}

func GetMimeType(ext string) (string, bool) {
	mime, ok := mimes[ext]
	return mime, ok
}

